def build_defense_table():
    """DAPPER retrained on defended traffic (train.py --defense): macro-F1 and byte overhead per fleet."""
    def cell(net, d):
        p = os.path.join(RUNS, "%st_dapper_s1_def%s.json" % (net, d))
        if not os.path.exists(p):
            return "--", "--"
        j = json.load(open(p))
        return "$%.3f$" % j["overall"]["macro_f1"], "$%+.0f\\%%$" % (100 * j["overhead"])
    da, _ = agg("At", "dapper"); db, _ = agg("Bt", "dapper")
    rows = ["None (undefended) & %s & $0\\%%$ & %s & $0\\%%$ \\\\" % ("--" if da is None else "$%.3f$" % da, "--" if db is None else "$%.3f$" % db)]
    for d in ("pad256", "pad512", "jitter200", "const"):
        a, ao = cell("A", d); b, bo = cell("B", d)
        rows.append("%s & %s & %s & %s & %s \\\\" % (DEFN[d], a, ao, b, bo))
    t = ("\\begin{table}[!htb]\n\\centering\n\\caption{{\\bf Traffic-shaping defences: residual leakage versus cost.} "
         "Held-out macro-F1 of DAPPER retrained on the defended traffic (operational state, seed 1) and the byte overhead "
         "of each countermeasure relative to the undefended capture.}\n"
         "\\label{tab:defense}\n\\begin{tabular}{lcccc}\n\\toprule\n"
         " & \\multicolumn{2}{c}{Multirotor} & \\multicolumn{2}{c}{VTOL} \\\\\n"
         "Defence & Macro-F1 & Overhead & Macro-F1 & Overhead \\\\\n\\midrule\n" + "\n".join(rows)
         + "\n\\bottomrule\n\\end{tabular}\n\\end{table}\n")
    open(os.path.join(PAPER, "auto_table_defense.tex"), "w").write(t)


