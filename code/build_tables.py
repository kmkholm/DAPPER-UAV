def load(net, m, s, ho=""):
    p = os.path.join(RUNS, "%s_%s_s%d%s.json" % (net, m, s, "_ho" + ho if ho else ""))
    return json.load(open(p)) if os.path.exists(p) else None


def agg(net, m, key="macro_f1"):
    v = [load(net, m, s)["overall"][key] for s in (1, 2, 3) if load(net, m, s)]
    return (np.mean(v), np.std(v)) if v else (None, None)


def fmt(mu, sd):
    return "--" if mu is None else ("$%.3f \\pm %.3f$" % (mu, sd))


def macro(name, val):
    return "\\newcommand{\\%s}{%s}\n" % (name, val)


def build_macros():
    s = "% auto-generated by build_tables.py -- do not edit\n"
    for k, v in CFG.items():
        s += macro(k, v)
    da, _ = agg("At", "dapper"); db, _ = agg("Bt", "dapper")
    fa, _ = agg("At", "fedavg"); fb, _ = agg("Bt", "fedavg")
    sa, _ = agg("At", "dapper_softmax")
    fine, _ = agg("A", "dapper"); fineb, _ = agg("B", "dapper")
    oa, _ = agg("Ac", "dapper"); ob, _ = agg("Bc", "dapper")
    s += macro("FineMacroA", "--" if fine is None else "%.3f" % fine)
    s += macro("FineMacroB", "--" if fineb is None else "%.3f" % fineb)
    s += macro("OpFourA", "--" if oa is None else "%.3f" % oa)
    s += macro("OpFourB", "--" if ob is None else "%.3f" % ob)
    names = {"local": "Local", "central": "Central", "fedavg": "FedAvg", "fedprox": "FedProx", "fedbn": "FedBN", "dapper": "Dapper"}
    for net in "AB":
        for m, nm in names.items():
            v, _ = agg(net + "t", m); s += macro("OS%s%s" % (nm, net), "--" if v is None else "%.3f" % v)
            v, _ = agg(net + "c", m); s += macro("OF%s%s" % (nm, net), "--" if v is None else "%.3f" % v)
            v, _ = agg(net, m); s += macro("FK%s%s" % (nm, net), "--" if v is None else "%.3f" % v)
        v, _ = agg(net + "t", "dapper_nobins"); s += macro("StatsOnly" + net, "--" if v is None else "%.3f" % v)
    s += macro("DapperMacroA", "--" if da is None else "%.3f" % da)
    s += macro("DapperMacroB", "--" if db is None else "%.3f" % db)
    s += macro("DapperGainA", "--" if (da is None or fa is None) else "%.2f" % (100 * (da - fa)))
    s += macro("DapperGainB", "--" if (db is None or fb is None) else "%.2f" % (100 * (db - fb)))
    s += macro("AblSoftmaxA", "--" if (da is None or sa is None) else "%.1f" % (100 * (da - sa)))
    # total windows from processed summary
    tw = None
    sp = os.path.join(PROC, "summary.json")
    if os.path.exists(sp):
        pass  # windows counted below from npz
    s += macro("TotalWindows", "--" if tw is None else "%s" % tw)
    # prior-work granularity (airborne vs ground) from the operational-task posteriors of DAPPER
    try:
        from sklearn.metrics import roc_auc_score, accuracy_score
        for net in "AB":
            acc, auc = [], []
            for seed in (1, 2, 3):
                p = os.path.join(RUNS, "%st_dapper_s%d_pred.npz" % (net, seed))
                if not os.path.exists(p):
                    continue
                d = np.load(p); y = d["y"]; pr = d["prob"].astype(float)
                acc.append(accuracy_score(y == 0, d["yp"] == 0)); auc.append(roc_auc_score((y != 0).astype(int), 1 - pr[:, 0]))
            s += macro("BinAcc" + net, "--" if not acc else "%.1f" % (100 * np.mean(acc)))
            s += macro("BinAuc" + net, "--" if not auc else "%.3f" % np.mean(auc))
    except Exception:
        for net in "AB":
            s += macro("BinAcc" + net, "--") + macro("BinAuc" + net, "--")
    # stream-level smoothing (eval_stream.py --json) if available
    for net in "AB":
        p = os.path.join(RUNS, "stream_%st.json" % net)
        v = json.load(open(p)) if os.path.exists(p) else None
        s += macro("SmoothF" + net, "--" if not v else "%.3f" % v["k5"]["op_f1"])
        s += macro("SmoothAcc" + net, "--" if not v else "%.1f" % (100 * v["k5"]["op_acc"]))
    open(os.path.join(PAPER, "auto_macros.tex"), "w").write(s)
    return da, db


def count_windows():
    import sys
    sys.path.insert(0, HERE)
    try:
        from data import load_network
        n = 0
        for net in "AB":
            X, clients, _ = load_network(PROC, net)
            for d in clients.values():
                n += int((d["split"] >= 0).sum())
        return n
    except Exception:
        return None


def build_main_table():
    rows = []
    for m in MAIN:
        a = fmt(*agg("A", m)); b = fmt(*agg("B", m))
        bold = m == "dapper"
        lab = ("\\textbf{%s}" % MLAB[m]) if bold else MLAB[m]
        if bold:
            a = a.replace("$", "$\\mathbf{", 1).replace("\\pm", "}\\pm") if a != "--" else a
        rows.append("%s & %s & %s \\\\" % (lab, fmt(*agg("At", m)), fmt(*agg("Bt", m))))
    t = ("\\begin{table}[!htb]\n\\centering\n\\caption{{\\bf Held-out macro-F1 by training method (operational state: ground / autonomous flight / tele-operation).} "
         "Mean $\\pm$ s.d. over \\NSeeds{} seeds; all methods share the same encoder. "
         "Central pools all sites and is a reference not available to a distributed observer.}\n"
         "\\label{tab:main}\n\\begin{tabular}{lcc}\n\\toprule\n"
         "Method & Multirotor (WireGuard) & VTOL (IPsec) \\\\\n\\midrule\n"
         + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n\\end{table}\n")
    open(os.path.join(PAPER, "auto_table_main.tex"), "w").write(t)


