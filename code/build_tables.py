def prior(tag):
    p = os.path.join(RUNS, "prior_%s.json" % tag)
    return json.load(open(p)) if os.path.exists(p) else {}


def build_prior_table():
    """Prior-work pipelines (prior_baselines.py) next to DAPPER on the same windows and splits, at the three granularities."""
    rows = []
    P = {t: prior(t) for t in ("At", "Bt", "Ac", "Bc", "A", "B")}
    def cell(tag, k, m="op_f1"):
        d = P[tag]
        return "--" if k not in d else "%.3f" % d[k][m]
    for key, lab in (("Random forest (size + IAT statistics) | per site", "Size/IAT statistics + random forest, per site~\\cite{sciancalepore2019,pinch2020}"),
                     ("Random forest (size + IAT statistics) | pooled", "Size/IAT statistics + random forest, pooled"),
                     ("SVM-RBF (size + IAT statistics) | per site", "Size/IAT statistics + SVM, per site~\\cite{alipourfanid2020}"),
                     ("SVM-RBF (size + IAT statistics) | pooled", "Size/IAT statistics + SVM, pooled")):
        rows.append("%s & %s & %s & %s & %s & %s & %s \\\\" % (lab, cell("At", key), cell("Bt", key), cell("Ac", key), cell("Bc", key),
                                                             cell("A", key, "fine_f1"), cell("B", key, "fine_f1")))
    vals = [agg(t, "dapper")[0] for t in ("At", "Bt", "Ac", "Bc", "A", "B")]
    rows.append("\\textbf{DAPPER, federated (this work)} & " + " & ".join("--" if v is None else "\\textbf{%.3f}" % v for v in vals) + " \\\\")
    t = ("\\begin{table}[!htb]\n\\centering\n\\caption{{\\bf Prior traffic-analysis pipelines on the same data, at three granularities.} "
         "The published UAV traffic-analysis approaches use statistics of packet sizes and inter-arrival times with classical learners; "
         "we rebuild them from the raw packets of the same windows and evaluate them on the same held-out sorties, per site (as in those "
         "single-vantage studies, one model per observer) and pooled (all observers share raw data). Held-out macro-F1 for the operational "
         "state (ground / autonomous flight / tele-operation), the operational phases (adds stationary versus transit) and the fine kinematic "
         "phases. DAPPER is trained federatedly, i.e.\\ without pooling raw traffic.}\n\\label{tab:prior}\n\\begin{tabular}{lcccccc}\n\\toprule\n"
         " & \\multicolumn{2}{c}{Operational state} & \\multicolumn{2}{c}{Operational phases} & \\multicolumn{2}{c}{Kinematic phases} \\\\\n"
         "Method & Multirotor & VTOL & Multirotor & VTOL & Multirotor & VTOL \\\\\n\\midrule\n" + "\n".join(rows)
         + "\n\\bottomrule\n\\end{tabular}\n\\end{table}\n")
    open(os.path.join(PAPER, "auto_table_prior.tex"), "w").write(t)


